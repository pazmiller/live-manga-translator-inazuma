const delay=ms=>new Promise(r=>setTimeout(r,ms));
async function until(check,timeout=3000) {
  const start=Date.now();
  while(Date.now()-start<timeout) {if(await check()) return;await delay(20);}
  throw new Error('Timed out waiting for renderer state');
}
async function snapshot(win,name) {
  // Hidden windows can retain an older compositor frame until explicitly painted.
  await win.webContents.executeJavaScript(`Promise.all([...document.images].filter(img=>img.getAttribute('src')).map(img=>img.decode()))`);
  win.webContents.invalidate();await win.webContents.capturePage();await delay(80);
  fs.writeFileSync(path.join(root,'.qa',name),(await win.webContents.capturePage()).toPNG());
}
