  await until(()=>evaluate(`document.querySelector('#lock span').textContent==='翻译选区'`));
  assert.equal(await evaluate(`document.getElementById('message').hidden`),true,'Retry clears old error');
  await evaluate(`document.getElementById('restorePrevious').click()`);await until(()=>restoreCalls===1);
  await until(()=>evaluate(`document.getElementById('status').textContent==='已恢复上一版 · 6 处'`));
  frame.webContents.send('frame:recovery',{available:false,canRestore:false,completed:0,total:0});await delay(30);
